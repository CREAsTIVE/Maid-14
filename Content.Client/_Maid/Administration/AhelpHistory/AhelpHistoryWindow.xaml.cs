using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Maid.Administration.AhelpHistory;

/// <summary>
/// Shows a player's ahelp dialogs, newest round first, each dialog read top to bottom.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AhelpHistoryWindow : FancyWindow
{
    public event Action? OnLoadMore;

    /// <summary>
    /// Raised with the round id of a dialog the user wants to read whole.
    /// </summary>
    public event Action<int?>? OnOpenFullDialog;

    private AhelpHistoryEuiState? _state;

    /// <summary>
    /// Labels created by the last rebuild. Their first measure can come out empty, which makes dialogs
    /// overlap until the next layout pass, so they are re-measured on the following frames.
    /// </summary>
    private readonly List<Control> _labels = new();
    private int _remeasureFrames;

    public AhelpHistoryWindow()
    {
        RobustXamlLoader.Load(this);

        LoadMoreButton.OnPressed += _ => OnLoadMore?.Invoke();
        FilterLineEdit.OnTextChanged += _ => Rebuild();
    }

    public void SetState(AhelpHistoryEuiState state)
    {
        _state = state;
        Title = Loc.GetString("ahelp-history-window-title", ("player", state.PlayerName));

        LoadMoreButton.Visible = state.HasMore || state.Loading;
        LoadMoreButton.Disabled = state.Loading;
        LoadMoreButton.Text = state.Loading
            ? Loc.GetString("ahelp-history-loading")
            : Loc.GetString("ahelp-history-load-older");

        Rebuild();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_remeasureFrames <= 0)
            return;

        _remeasureFrames--;

        foreach (var label in _labels)
        {
            label.InvalidateMeasure();
        }

        DialogsContainer.InvalidateMeasure();
    }

    private void Rebuild()
    {
        DialogsContainer.RemoveAllChildren();
        _labels.Clear();

        if (_state == null)
            return;

        var filter = FilterLineEdit.Text.Trim();
        var shownDialogs = 0;

        foreach (var dialog in _state.Dialogs)
        {
            var entries = dialog.Preview
                .Where(e => filter.Length == 0
                            || e.Message.Contains(filter, StringComparison.OrdinalIgnoreCase)
                            || e.SenderName.Contains(filter, StringComparison.OrdinalIgnoreCase))
                .ToList();

            if (entries.Count == 0)
                continue;

            shownDialogs++;
            DialogsContainer.AddChild(CreateDialogControl(dialog, entries));
        }

        CountLabel.Text = filter.Length == 0
            ? Loc.GetString("ahelp-history-count", ("count", _state.Dialogs.Count))
            : Loc.GetString("ahelp-history-count-filtered", ("shown", shownDialogs), ("count", _state.Dialogs.Count));

        EmptyLabel.Visible = !_state.Loading && _state.Dialogs.Count == 0;

        DialogsContainer.InvalidateMeasure();
        Scroll.InvalidateMeasure();
        _remeasureFrames = 2;
    }

    private Control CreateDialogControl(AhelpHistoryDialog dialog, List<AhelpHistoryEntry> entries)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 10),
        };

        var header = new RichTextLabel { HorizontalExpand = true };
        header.SetMessage(AhelpHistoryFormatter.FormatHeaderMessage(
            dialog.RoundId, dialog.ServerName, dialog.StartedAt, dialog.MessageCount));
        box.AddChild(header);
        _labels.Add(header);

        var text = new FormattedMessage();
        for (var i = 0; i < entries.Count; i++)
        {
            if (i > 0)
                text.AddText("\n");

            AhelpHistoryFormatter.AppendEntry(text, entries[i]);
        }

        var body = new RichTextLabel { HorizontalExpand = true };
        body.SetMessage(text);
        box.AddChild(body);
        _labels.Add(body);

        if (dialog.Truncated)
        {
            var more = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            more.AddChild(new Label
            {
                Text = Loc.GetString("ahelp-history-preview-shown",
                    ("shown", dialog.Preview.Count),
                    ("count", dialog.MessageCount)),
                FontColorOverride = Color.FromHex("#a0a0a0"),
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 8, 0),
            });

            var button = new Button { Text = Loc.GetString("ahelp-history-open-full-dialog") };
            var roundId = dialog.RoundId;
            button.OnPressed += _ => OnOpenFullDialog?.Invoke(roundId);
            more.AddChild(button);

            box.AddChild(more);
        }

        return box;
    }
}
