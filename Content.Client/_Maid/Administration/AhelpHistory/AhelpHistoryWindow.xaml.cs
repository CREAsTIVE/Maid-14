using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Maid.Administration.AhelpHistory;

[GenerateTypedNameReferences]
public sealed partial class AhelpHistoryWindow : FancyWindow
{
    private static readonly Color HeaderColor = Color.FromHex("#a0a0a0");
    private static readonly Color AdminColor = Color.FromHex("#ff5555");
    private static readonly Color AdminOnlyColor = Color.FromHex("#ffaa00");

    public event Action? OnLoadMore;

    private AhelpHistoryEuiState? _state;
    private bool _scrolledInitially;

    public AhelpHistoryWindow()
    {
        RobustXamlLoader.Load(this);

        LoadMoreButton.OnPressed += _ => OnLoadMore?.Invoke();
        FilterLineEdit.OnTextChanged += _ => Rebuild();
    }

    public void SetState(AhelpHistoryEuiState state)
    {
        _state = state;
        Title = Loc.GetString("ahelp-history-window-title", ("player", state.PlayerName));
        LoadMoreButton.Disabled = !state.HasMore || state.Loading;

        Rebuild();

        if (!_scrolledInitially && !state.Loading && state.Entries.Count > 0)
        {
            _scrolledInitially = true;
            Output.ScrollToBottom();
        }
    }

    private void Rebuild()
    {
        Output.Clear();

        if (_state == null)
            return;

        var filter = FilterLineEdit.Text.Trim();
        var entries = _state.Entries
            .Where(e => filter.Length == 0
                        || e.Message.Contains(filter, StringComparison.OrdinalIgnoreCase)
                        || e.SenderName.Contains(filter, StringComparison.OrdinalIgnoreCase))
            .ToList();

        CountLabel.Text = _state.Loading
            ? Loc.GetString("ahelp-history-loading")
            : filter.Length == 0
                ? Loc.GetString("ahelp-history-count", ("count", _state.Entries.Count))
                : Loc.GetString("ahelp-history-count-filtered",
                    ("shown", entries.Count),
                    ("count", _state.Entries.Count));

        if (_state.Entries.Count == 0)
        {
            if (!_state.Loading)
                Output.AddText(Loc.GetString("ahelp-history-empty"));
            return;
        }

        var first = true;
        int? lastRound = null;
        string? lastServer = null;

        foreach (var entry in entries)
        {
            if (first || entry.RoundId != lastRound || entry.ServerName != lastServer)
            {
                first = false;
                lastRound = entry.RoundId;
                lastServer = entry.ServerName;
                Output.AddMessage(FormatHeader(entry));
            }

            Output.AddMessage(FormatEntry(entry));
        }
    }

    private static FormattedMessage FormatHeader(AhelpHistoryEntry entry)
    {
        var msg = new FormattedMessage();
        msg.PushColor(HeaderColor);

        var text = entry.RoundId is { } roundId
            ? Loc.GetString("ahelp-history-round-header",
                ("round", roundId.ToString()),
                ("server", entry.ServerName ?? "?"),
                ("date", ToLocal(entry.SentAt).ToString("yyyy-MM-dd")))
            : Loc.GetString("ahelp-history-no-round-header");

        msg.AddText($"--- {text} ---");
        msg.Pop();
        return msg;
    }

    private static FormattedMessage FormatEntry(AhelpHistoryEntry entry)
    {
        var msg = new FormattedMessage();
        msg.AddText($"[{ToLocal(entry.SentAt):HH:mm}] ");

        if (entry.AdminOnly)
        {
            msg.PushColor(AdminOnlyColor);
            msg.AddText(Loc.GetString("ahelp-history-admin-only-prefix") + " ");
            msg.Pop();
        }

        if (entry.SenderIsAdmin)
            msg.PushColor(AdminColor);

        var sender = entry.SenderName;
        if (entry.FromWebhook)
            sender += " " + Loc.GetString("ahelp-history-discord-suffix");

        msg.AddText(sender);

        if (entry.SenderIsAdmin)
            msg.Pop();

        msg.AddText(": " + entry.Message);
        return msg;
    }

    private static DateTime ToLocal(DateTime utc)
    {
        return DateTime.SpecifyKind(utc, DateTimeKind.Utc).ToLocalTime();
    }
}
