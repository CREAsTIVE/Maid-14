using Content.Client.UserInterface.Controls;
using Content.Shared._Maid.Administration.AhelpHistory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Maid.Administration.AhelpHistory;

/// <summary>
/// Shows one whole ahelp dialog, oldest message first.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AhelpDialogWindow : FancyWindow
{
    public AhelpDialogWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetDialog(AhelpHistoryEuiMsg.FullDialogResponse dialog)
    {
        Title = Loc.GetString("ahelp-history-full-dialog-title", ("player", dialog.PlayerName));

        var startedAt = dialog.Entries.Count > 0 ? dialog.Entries[0].SentAt : DateTime.UtcNow;

        Output.Clear();
        Output.AddMessage(AhelpHistoryFormatter.FormatHeaderMessage(
            dialog.RoundId,
            dialog.ServerName,
            startedAt,
            dialog.Entries.Count));

        foreach (var entry in dialog.Entries)
        {
            Output.AddMessage(AhelpHistoryFormatter.FormatEntry(entry));
        }
    }
}
